#!/usr/bin/env node
/**
 * Builds a single SQL file that installs AgroJC into a dedicated Postgres schema
 * (default "agrojc") instead of "public", so it can share a Supabase project with
 * another application without touching its tables.
 *
 *   node scripts/build-schema-sql.mjs [schema] [bucket] > agrojc.sql
 *
 * Then set NEXT_PUBLIC_SUPABASE_SCHEMA=<schema> and
 * NEXT_PUBLIC_SUPABASE_LISTINGS_BUCKET=<bucket>, and add the schema to
 * Supabase → Settings → API → Exposed schemas.
 */
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const schema = process.argv[2] ?? "agrojc";
const bucket = process.argv[3] ?? `${schema}-listings`;
if (!/^[a-z_][a-z0-9_]*$/.test(schema)) throw new Error("invalid schema name");
if (!/^[a-z0-9-]+$/.test(bucket)) throw new Error("invalid bucket name");

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase");
const files = [...readdirSync(join(root, "migrations")).sort().map((f) => join(root, "migrations", f)), join(root, "seed.sql")];

const rewrite = (sql) =>
  sql
    .replace(/\bpublic\./g, `${schema}.`)
    .replace(/search_path = public\b/g, `search_path = ${schema}`)
    .replace(/'listings'/g, `'${bucket}'`)
    // storage.objects is shared with the other app: namespace our policy names.
    .replace(/create policy "([^"]+)" on storage\./g, `create policy "${schema}: $1" on storage.`);

const header = `-- Generated by scripts/build-schema-sql.mjs — do not edit by hand.
begin;
create schema if not exists ${schema};
grant usage on schema ${schema} to anon, authenticated, service_role;
alter default privileges in schema ${schema} grant all on tables to anon, authenticated, service_role;
alter default privileges in schema ${schema} grant all on functions to anon, authenticated, service_role;
alter default privileges in schema ${schema} grant all on sequences to anon, authenticated, service_role;
`;

const body = files.map((f) => `\n-- ───── ${f.split("/").slice(-2).join("/")}\n${rewrite(readFileSync(f, "utf8"))}`).join("\n");
process.stdout.write(`${header}${body}\ncommit;\nnotify pgrst, 'reload schema';\n`);
